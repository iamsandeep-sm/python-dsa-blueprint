
# ? Take two numbers as input and print their sum, difference, product and quotient.

num1 = int(input("Enter any number : "))
num2 = int(input("Enter any number : "))
sum = num1 + num2
diff = num1 - num2
prod = num1 * num2
quot = num1 / num2  #* for integer quotient a // b for a / b for float quotient
rem = num1 % num2
print(f"The sum of your entered number is {sum}")
print(f"The difference of your entered number is {diff}")
print(f"The product of your entered number is {prod}")
print(f"The quotient of your entered number is {quot}")
print(f"The remainder of your entered number is {rem}")

