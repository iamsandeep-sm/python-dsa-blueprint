# * The / and // both are the operator in programming language. in python the main difference is ' / ' this operator provide result along with the decimal value, whereas the ' // ' this operator provide result without decimal values....

n1 = 15
n2 = 3

print(f"By using  / operator in these number result is : {n1 / n2}")          # output : 5.0
print(f"By using // operator in these number result is : {n1 // n2}")         # output : 5
